import Foundation

// OWNER: WS-R6 文件角色与扫描范围（RD-14）—— 文件角色判据（纯函数，不碰磁盘）。
//
// 这一档以前**完全不存在**：`Services/Code/**` 里 grep `role|generated|isTest|fixture` 在
// 本文件落地之前是 0 命中（台账 §7.2 的 RD-14/15 那格记的就是这件事）。于是一份 5 行的
// `README.md` 与一份 5 万行的生产码在 `codeLines` 里同分母，`.pb.swift` 与手写码同分母，
// 谁也没说过话。
//
// 设计约束（三条，改之前先读）：
// 1. **每条判定必须带出处**：`SourceFileRoleDecision.criterion` 说明是哪条判据、
//    `evidence` 说明命中的是哪个路径段/后缀/文件头短语。"默默归类"就是本条要消灭的东西。
// 2. **认不出来要有地方去**：`unrecognized` 是一等档，只由 `.noRoleEvidence` 这一条来路进入。
//    语言表新增一种语言而没在这里登记家族时，它的文件会落进 `unrecognized` ——
//    这是刻意的：漏判必须显形，不许由"看着像源码"兜底成生产码。
//    （`SourceRoleTruthTests.testEverySupportedLanguageHasARoleFamily` 钉住这条。）
// 3. **弱判定要单独点名**：只凭语言（路径没有任何角色线索）判成生产码的，走
//    `.productionLanguageOnly`，在台账里与 `.productionPathSegment` 分开计数。
//    把它并进生产码 = 把"没认出来"说成"这就是产品代码"。

// MARK: - 七个角色 + 一个兜底档

enum SourceFileRole: String, CaseIterable, Sendable {
    case production
    case test
    case generated
    case configuration
    case documentation
    case buildArtifact
    case backupEvidence
    case unrecognized

    var displayName: String {
        switch self {
        case .production: return "生产源码"
        case .test: return "测试与夹具"
        case .generated: return "生成物"
        case .configuration: return "配置与结构化数据"
        case .documentation: return "文档"
        case .buildArtifact: return "构建与发布产物"
        case .backupEvidence: return "备份与历史证据"
        case .unrecognized: return "角色未识别"
        }
    }
}

/// 判据名字。每条都必须能在 `SourceFileRoleRule` 里找到唯一一个使用点 ——
/// 单测 `testEveryCriterionIsActuallyUsed` 钉这条，防止判据表里留着一条没人走的分支。
enum SourceRoleCriterion: String, CaseIterable, Sendable {
    case buildArtifactPath          // 路径段命中产物目录/后缀（xcarchive / DerivedData / *.app …）
    case backupEvidenceName         // 文件名形状：`.bak`、`.orig`、`~`、带日期的 dump
    case backupEvidencePath         // 路径段命中 backup / archive / old
    case lockFileName               // package-lock.json / Cargo.lock / Podfile.lock …
    case generatedPathSegment       // generated / gen / protobuf 产物目录
    case generatedFileSuffix        // .pb.swift / _pb2.py / .g.dart / .generated.* …
    case generatedHeaderLine        // 文件头写着 Code generated by … / DO NOT EDIT
    case migrationShape             // db/migrate、NNNN_*.sql、V1__x.sql
    case testPathSegment            // spec / __tests__ / it / e2e / src/test / *Tests 目录
    case testFileNameShape          // foo_test.go / test_foo.py / *.spec.ts / FooTests.swift
    case configurationPathSegment   // config / configs / i18n / .github/workflows
    case configurationDataLanguage  // YAML/TOML/JSON/XML/Properties/INI 这类结构化数据语言
    case buildScriptLanguage        // Dockerfile / Makefile / Gradle / Shell（构建脚本，见下方边界说明）
    case documentationExtension     // Markdown
    case documentationPathSegment   // docs / documentation / wiki
    case productionPathSegment      // src / Sources / lib / app / cmd / internal + 编程语言
    case productionLanguageOnly     // 只有语言证据、路径毫无角色线索 ⇒ 弱判定，单独计数
    case noRoleEvidence             // 进入 `unrecognized` 的唯一来路
}

/// 一条判定：角色 + 判据 + 命中的原文线索（可点名，供台账与后续 UI 复述）。
struct SourceFileRoleDecision: Sendable, Equatable {
    var role: SourceFileRole
    var criterion: SourceRoleCriterion
    var evidence: String

    init(_ role: SourceFileRole, _ criterion: SourceRoleCriterion, _ evidence: String) {
        self.role = role
        self.criterion = criterion
        self.evidence = evidence
    }
}

extension SourceRoleCriterion {
    /// 判据 ⇒ 角色。**这一份对应关系只在这里定义一次**；`decide` 走出来的角色必须与它一致
    /// （`SourceRoleTruthTests.testEveryCriterionMapsToItsOwnRole` 逐条对账）。
    /// 立这条的理由：判据名字与角色分在两处写，迟早会出现"`\.lockFileName` 判成配置"这种自相矛盾。
    var role: SourceFileRole {
        switch self {
        case .buildArtifactPath: return .buildArtifact
        case .backupEvidenceName, .backupEvidencePath: return .backupEvidence
        case .lockFileName, .generatedPathSegment, .generatedFileSuffix,
             .generatedHeaderLine, .migrationShape: return .generated
        case .testPathSegment, .testFileNameShape: return .test
        case .configurationPathSegment, .configurationDataLanguage, .buildScriptLanguage: return .configuration
        case .documentationExtension, .documentationPathSegment: return .documentation
        case .productionPathSegment, .productionLanguageOnly: return .production
        case .noRoleEvidence: return .unrecognized
        }
    }
}

// MARK: - 判据本体

enum SourceFileRoleRule {

    /// 判一个文件的角色。`relativePath` 必须是相对被扫根的路径（`ScannedSourceFile.relativePath`），
    /// `headerLines` 是文件前若干行原文（只用于「文件头声明自己是生成物」这一条判据）。
    ///
    /// 顺序即优先级，**先具体后一般**：产物/备份 → 生成物 → 测试 → 配置/文档 → 生产码 → 未识别。
    /// 保留边界（不装作用域已覆盖）见文件头下方的「判序理由」。
    static func decide(relativePath: String, language: String?, headerLines: [String] = [])
        -> SourceFileRoleDecision {
        let segments = pathSegments(relativePath)
        let fileName = segments.last ?? relativePath
        if let hit = artifactDecision(segments: segments) { return hit }
        if let hit = backupDecision(fileName: fileName, segments: segments) { return hit }
        if let hit = generatedDecision(fileName: fileName, segments: segments, headerLines: headerLines,
                                      language: language) {
            return hit
        }
        if let hit = testDecision(fileName: fileName, segments: segments) { return hit }
        if let hit = dataAndDocumentationDecision(fileName: fileName, segments: segments, language: language) {
            return hit
        }
        return productionDecision(fileName: fileName, segments: segments, language: language)
    }

    /// 相对路径 → 路径段（不含空段）。Windows 反斜杠不在本工具的支持面内（扫描根由 `URL` 给出）。
    static func pathSegments(_ relativePath: String) -> [String] {
        relativePath.split(separator: "/").map(String.init)
    }

    // MARK: 测试码    // MARK: 测试码

    static func testDecision(fileName: String, segments: [String]) -> SourceFileRoleDecision? {
        for segment in segments.dropLast() {
            if testDirectoryNames.contains(segment.lowercased()) {
                return SourceFileRoleDecision(.test, .testPathSegment, segment)
            }
            // Xcode / Maven 习惯的 `<Module>Tests` 目录名。**大小写敏感**：按小写比会让
            // `contest/`、`attest/` 这类英文词整棵子树被判成测试码（本仓既有教训：名字像≠语义对）。
            for tail in directoryTestTails where segment.hasSuffix(tail) && segment.count > tail.count {
                return SourceFileRoleDecision(.test, .testPathSegment, segment)
            }
        }
        let lower = fileName.lowercased()
        for suffix in testFileNameSuffixes where lower.hasSuffix(suffix) {
            return SourceFileRoleDecision(.test, .testFileNameShape, suffix)
        }
        for prefix in testFileNamePrefixes where lower.hasPrefix(prefix) {
            return SourceFileRoleDecision(.test, .testFileNameShape, prefix)
        }
        if let stem = nonEmptyStem(of: fileName), testStemTails.contains(where: { stem.hasSuffix($0) }) {
            return SourceFileRoleDecision(.test, .testFileNameShape, fileName)
        }
        return nil
    }

    static let directoryTestTails: [String] = ["Tests", "Test", "Spec", "Specs", "UITests"]

    /// 目录名。`it` 与 `e2e` 是刻意收进来的两类小众命名 ——
    /// 工单点名的"只认 tests/ 就漏判"正是这里以前缺的东西。
    static let testDirectoryNames: Set<String> = [
        "tests", "test", "spec", "specs", "__tests__", "__mocks__", "e2e", "it",
        "features", "cypress", "playwright", "puppeteer", "selenium", "unittests",
        "integrationtests", "androidtest", "ist", "qa",
    ]

    static let testFileNameSuffixes: [String] = [
        ".test.js", ".test.jsx", ".test.ts", ".test.tsx", ".spec.js", ".spec.ts", ".spec.tsx",
        "_test.go", "_test.py", "_spec.rb", "_test.rb", ".test.swift",
    ]

    static let testFileNamePrefixes: [String] = ["test_", "spec_"]

    /// 大小写敏感的词尾（Swift/Java/Kotlin/C# 一族用 `FooTests.swift` / `FooTest.java`）。
    /// 只在**词边界**上比：`Latest`、`protest` 这类词干不配当测试。
    static let testStemTails: [String] = ["Test", "Tests", "Spec", "IT", "TestCase"]

    static func nonEmptyStem(of fileName: String) -> String? {
        let stem = (fileName as NSString).deletingPathExtension
        return stem.isEmpty ? nil : stem
    }

    // MARK: 配置 / 数据 / 文档

    static func dataAndDocumentationDecision(fileName: String, segments: [String], language: String?)
        -> SourceFileRoleDecision? {
        for segment in segments.dropLast() {
            let lower = segment.lowercased()
            if configurationDirectoryNames.contains(lower) {
                return SourceFileRoleDecision(.configuration, .configurationPathSegment, segment)
            }
            if documentationDirectoryNames.contains(lower) {
                return SourceFileRoleDecision(.documentation, .documentationPathSegment, segment)
            }
        }
        if language == "Markdown" {
            return SourceFileRoleDecision(.documentation, .documentationExtension, fileName)
        }
        if let language, buildScriptLanguages.contains(language) {
            return SourceFileRoleDecision(.configuration, .buildScriptLanguage, language)
        }
        if let language, configurationDataLanguages.contains(language) {
            return SourceFileRoleDecision(.configuration, .configurationDataLanguage, language)
        }
        return nil
    }

    static let configurationDirectoryNames: Set<String> = [
        "config", "configs", "configuration", "i18n", "l10n", "locales", "settings",
        ".github", "workflows", "deploy", "deployment", "helm", "chart",
    ]

    static let documentationDirectoryNames: Set<String> = [
        "docs", "doc", "documentation", "wiki", "guides", "handbook", "notes",
    ]

    /// 结构化数据语言：它们的行**不是**"人写的逻辑"，与生产码同分母时读数没有意义（RD-20 的另一半）。
    static let configurationDataLanguages: Set<String> = [
        "YAML", "TOML", "JSON", "XML", "Properties", "INI",
    ]

    /// 构建脚本。RD-14 的七档里没有"构建脚本"这一档，本流**不擅自新增第八档**，
    /// 先落在「配置与结构化数据」并用 `.buildScriptLanguage` 单独点名 ——
    //  要不要为它开一档，写进交回汇报的契约缺口由总工裁。
    static let buildScriptLanguages: Set<String> = ["Dockerfile", "Makefile", "Gradle", "Shell"]

    // MARK: 生产码与兜底

    static func productionDecision(fileName: String, segments: [String], language: String?)
        -> SourceFileRoleDecision {
        let programming = language.map { programmingLanguages.contains($0) } ?? false
        if programming {
            for segment in segments.dropLast() where productionDirectoryNames.contains(segment.lowercased()) {
                return SourceFileRoleDecision(.production, .productionPathSegment, segment)
            }
            // 弱判定：**只**有语言证据。计数与生产码分开报（见 `SourceRoleTally.weakEvidenceFiles`）。
            return SourceFileRoleDecision(.production, .productionLanguageOnly, language ?? fileName)
        }
        // `SQL` 刻意不进编程语言族也不进配置族：一个裸 `.sql` 可能是 schema、迁移、
        // 报表查询、也可能是样例数据 —— 认不出来就落到未识别，不许猜。
        return SourceFileRoleDecision(.unrecognized, .noRoleEvidence, language ?? "无语言（后缀未收录）")
    }

    /// 手写源码的语言族。CSS/SCSS/HTML/Vue 算源码（前端手写），Protocol Buffers 算源码
    /// （`.proto` 是人写的 IDL，它的**产物** `.pb.*` 由 `generatedFileSuffixes` 接住）。
    static let programmingLanguages: Set<String> = [
        "Swift", "Java", "Kotlin", "TypeScript", "JavaScript", "Python", "Go", "Rust",
        "C", "C++", "Objective-C", "C#", "Ruby", "PHP", "Dart", "Scala", "Perl", "Lua",
        "Haskell", "Elixir", "R", "Vue", "HTML", "CSS", "SCSS", "Protocol Buffers",
    ]

    static let productionDirectoryNames: Set<String> = [
        "src", "source", "sources", "lib", "libs", "library", "app", "apps", "internal",
        "pkg", "cmd", "crates", "modules", "services", "core", "main",
    ]

    /// 语言表里**每一种**语言的家族归属，供守卫反查（新增语言未登记 ⇒ 落 `unrecognized`）。
    static func roleFamily(of language: String) -> String {
        if programmingLanguages.contains(language) { return "programming" }
        if configurationDataLanguages.contains(language) { return "data" }
        if buildScriptLanguages.contains(language) { return "buildScript" }
        if language == "Markdown" { return "documentation" }
        return "unmapped"
    }
}
