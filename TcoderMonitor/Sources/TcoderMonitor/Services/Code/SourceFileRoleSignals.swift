import Foundation

// OWNER: WS-R6 文件角色与扫描范围（RD-14）—— 角色判据的前三段名单与判定。
//
// 从 `SourceFileRoleRules.swift` **整块搬出**（400 行闸门，AGENTS §3 横切约束 4：
// 按类型整块搬去新文件才是修复）。判据、顺序、名单内容一字未改，
// 只是同一 `enum SourceFileRoleRule` 的第二片 —— 判定顺序仍由
// `SourceFileRoleRules.decide(relativePath:language:headerLines:)` 那一条链决定。
//
// 这一片管"最不该被当成生产码"的三类：构建与发布产物、备份与历史证据、生成码。
// 共同点：它们都是**机器造出来或留下来的**，与"人手写并要维护"的生产码
// 混在同一个 `codeLines` 分母里，读出来的规模与注释率都没有意义（RD-14 / RD-20）。

extension SourceFileRoleRule {

    // MARK: 构建与发布产物

    static func artifactDecision(segments: [String]) -> SourceFileRoleDecision? {
        for segment in segments.dropLast() {
            let lower = segment.lowercased()
            if artifactDirectoryNames.contains(lower) {
                return SourceFileRoleDecision(.buildArtifact, .buildArtifactPath, segment)
            }
            let ext = (lower as NSString).pathExtension
            if artifactDirectoryExtensions.contains(ext) {
                return SourceFileRoleDecision(.buildArtifact, .buildArtifactPath, segment)
            }
        }
        return nil
    }

    /// 目录**名**（整段相等）判产物。注意这些大多也住在 `ScanOptions.skipDirectories` 里，
    /// 正常扫描根本走不到这里 —— 留着的理由是：被扫项目可以把产物目录改名纳入
    /// （例如 `unpackage` 不在名单里、`Intermediate` 不在名单里）。
    static let artifactDirectoryNames: Set<String> = [
        "deriveddata", "intermediates", "unpackage", "archives", "ipa", "apk-output",
        "compileout", "published",
    ]

    /// 目录**后缀**判产物：`.xcarchive` 是本流实测到的那一条 —— 它既不在 `skipDirectories`
    /// 也不是 `packageExtensions`，但 Foundation 的 `.skipsPackageDescendants` 会因为
    /// 「目录里有 Info.plist」把它整个剪掉（见 `SourceScanTrail.consumeDirectoryEntry`）。
    static let artifactDirectoryExtensions: Set<String> = [
        "xcarchive", "xcbundle", "dsym", "ipa", "carthage", "bundle", "framework",
    ]

    // MARK: 备份与历史证据

    static func backupDecision(fileName: String, segments: [String]) -> SourceFileRoleDecision? {
        let lower = fileName.lowercased()
        if backupSuffixes.contains((lower as NSString).pathExtension) || lower.hasSuffix("~") {
            return SourceFileRoleDecision(.backupEvidence, .backupEvidenceName, fileName)
        }
        if hasDatedDumpSignature(lower) {
            return SourceFileRoleDecision(.backupEvidence, .backupEvidenceName, fileName)
        }
        for segment in segments.dropLast() where backupDirectoryNames.contains(segment.lowercased()) {
            return SourceFileRoleDecision(.backupEvidence, .backupEvidencePath, segment)
        }
        return nil
    }

    static let backupSuffixes: Set<String> = ["bak", "orig", "rej", "save", "swp", "swo", "old", "tmp"]
    static let backupDirectoryNames: Set<String> = ["backup", "backups", "archive", "trash", "prev"]
    /// `db-2024-01-01.sql` / `dump_2023.sql.gz` 这类"某天的历史导出"。
    static let datedDumpPattern = try! NSRegularExpression(pattern: #"(19|20)\d\d[-_.](0?[1-9]|1[0-2])[-_.](0?[1-9]|[12]\d|3[01])"#)

    static func hasDatedDumpSignature(_ text: String) -> Bool {
        datedDumpPattern.firstMatch(in: text, range: NSRange(location: 0, length: text.utf16.count)) != nil
    }

    // MARK: 生成码

    static func generatedDecision(fileName: String, segments: [String], headerLines: [String],
                                  language: String?) -> SourceFileRoleDecision? {
        let lower = fileName.lowercased()
        if lockFileNames.contains(lower) {
            return SourceFileRoleDecision(.generated, .lockFileName, fileName)
        }
        for suffix in generatedFileSuffixes where lower.hasSuffix(suffix) {
            return SourceFileRoleDecision(.generated, .generatedFileSuffix, suffix)
        }
        for segment in segments.dropLast() where generatedDirectoryNames.contains(segment.lowercased()) {
            return SourceFileRoleDecision(.generated, .generatedPathSegment, segment)
        }
        if migrationDecision(fileName: fileName, segments: segments) != nil {
            return SourceFileRoleDecision(.generated, .migrationShape, fileName)
        }
        // 文件头声明只对**编程语言**文件有效：Markdown / 数据文件里出现 "code generated by"
        // 通常是在讲生成器（教程、README），不是在声明自己是产物 —— 那是误报的另一半。
        if let language, roleFamily(of: language) == "programming" {
            for (offset, line) in headerLines.prefix(generatedHeaderScanLines).enumerated() {
                let payload = commentPayload(of: line)
                for marker in generatedHeaderMarkers where payload.hasPrefix(marker) {
                    return SourceFileRoleDecision(.generated, .generatedHeaderLine,
                                                  "第 \(offset + 1) 行以「\(marker)」开头")
                }
            }
        }
        return nil
    }

    /// 生成物的**文件名后缀**形状。`.pb.swift` 这类必须整串比，不能只看 `pathExtension`
    /// （`pathExtension` 只会给 `swift`，于是 protobuf 产物被读成手写 Swift —— 正是 RD-14 那格）。
    static let generatedFileSuffixes: [String] = [
        ".pb.swift", ".pb.cc", ".pb.h", ".pb.go", ".pb.dart", ".pb.cpp",
        "_pb2.py", "_pb2_grpc.py", ".pb.rb", "_pb.rb", ".pb.rbupdate",
        ".generated.swift", ".generated.kt", ".g.dart", ".freezed.dart", ".gr.dart",
        ".designer.cs", ".generated.cs", ".razor.cs", ".storyboard.swift",
        ".d.ts", ".min.js", ".min.css", ".gemspec.lock",
    ]

    static let generatedDirectoryNames: Set<String> = [
        "generated", "gen", "protobuf", "protoc", "buildinfo", ".next", "codegen",
    ]

    /// lock 文件。**RD-14 实测的口径分歧**：`yarn.lock` / `Cargo.lock` 今天走的是
    /// 「语言表不认这个后缀」而被剔除，`package-lock.json` / `pnpm-lock.yaml` 却因为
    /// 语言表认得 JSON/YAML 而被当普通源码统计 —— 同一种东西两句话。
    /// 这里把两族都认成 lock（生成物），被剔除的那些由 `SourceSkipLedger` 继续报。
    static let lockFileNames: Set<String> = [
        "package-lock.json", "pnpm-lock.yaml", "npm-shrinkwrap.json", "yarn.lock",
        "cargo.lock", "podfile.lock", "gemfile.lock", "composer.lock", "poetry.lock",
        "uv.lock", "mix.lock", "pubspec.lock", "go.sum", "deno.lock", "bun.lockb",
        "package.resolved", "uv.lockb",
    ]

    static let generatedHeaderMarkers: [String] = [
        "code generated by", "do not edit", "@generated", "autogenerated",
        "auto-generated", "this file was generated", "generated by protoc",
        "generated by the", "<auto-generated", "warning: generated",
    ]

    /// 只看前 8 行。生成物声明一律在头部，往后扫会把"教人怎么写生成器"的文档也读成生成物。
    static let generatedHeaderScanLines = 8

    /// 生成物声明必须是**位于注释开头的祈使句**（`// Code generated by …`、`# @generated`），
    /// 而不是句子里被提到的一次（`// 这篇教程会教你输出 code generated by 之类的字样`）。
    /// 与 TODO/FIXME 那套"只有注释形状里的标记才算欠账"同一条纪律：子串匹配就是误报。
    static func commentPayload(of line: String) -> String {
        String(line.lowercased().drop(while: { generatedHeaderLeaders.contains($0) }))
    }

    static let generatedHeaderLeaders = Set<Character>(" \t/*!<>?-\\[]{}%")

    /// 迁移文件：`NNNN_描述.sql`、`V1__描述.sql`（Flyway）、`db/migrate/`、`migrations/`。
    static func migrationDecision(fileName: String, segments: [String]) -> SourceFileRoleDecision? {
        for segment in segments.dropLast() {
            let lower = segment.lowercased()
            if lower == "migrations" || lower == "migrate" || lower == "flyway" || lower == "alembic" {
                return SourceFileRoleDecision(.generated, .migrationShape, segment)
            }
        }
        let stem = (fileName as NSString).deletingPathExtension
        if stem.range(of: #"^\d{1,6}_"#, options: .regularExpression) != nil { return migrationHit(fileName) }
        if stem.range(of: #"^[vV]\d+__"#, options: .regularExpression) != nil { return migrationHit(fileName) }
        return nil
    }

    private static func migrationHit(_ fileName: String) -> SourceFileRoleDecision {
        SourceFileRoleDecision(.generated, .migrationShape, fileName)
    }
}
