    }

    /// 生成物判据的**第二条腿**：只有文件头声明、路径上没有任何线索。
    func testGeneratedHeaderLineIsItsOwnCriterion() {
        assertRole("grpc/echo.js", "JavaScript",
                   header: ["/*", " * Code generated by protoc-gen-go. DO NOT EDIT.", " */"],
                   role: .generated, criterion: .generatedHeaderLine)
        let decision = SourceFileRoleRule.decide(relativePath: "grpc/echo.js", language: "JavaScript",
                                                 headerLines: ["// @generated"])
        XCTAssertTrue(decision.evidence.contains("@generated"), "线索要能指回原文：\(decision.evidence)")
    }

    // MARK: - 反例：合法写法不许误伤（名字像 ≠ 语义对）

    func testLookAlikeNamesAreNotMistakenForTestOrGenerated() {
        assertRole("src/LatestData.swift", "Swift", role: .production, criterion: .productionPathSegment)
        assertRole("contest/leaderboard.js", "JavaScript", role: .production,
                   criterion: .productionLanguageOnly)
        assertRole("src/Attic.swift", "Swift", role: .production, criterion: .productionPathSegment)
        assertRole("app/protest_handler.py", "Python", role: .production, criterion: .productionPathSegment)
        assertRole("src/MyTestBed.swift", "Swift", role: .production, criterion: .productionPathSegment)
        // 词尾 `IT` 只在**大写词边界**上算集成测试：`Wait.ts`、`Exit.ts` 这类英文词
        // 尾巴上确实挂着 "it"，把它们判成测试码就是把生产码的行数凭空搬走。
        assertRole("src/Wait.ts", "TypeScript", role: .production, criterion: .productionPathSegment)
        assertRole("src/Exit.ts", "TypeScript", role: .production, criterion: .productionPathSegment)
        assertRole("assets/notice.css", "CSS", role: .production, criterion: .productionLanguageOnly)
        // 生成物后缀必须**整串**比：`.swift` 单独看不该被当成 protobuf 产物
        assertRole("src/Widget.swift", "Swift", role: .production, criterion: .productionPathSegment)
        // 文件头里的"教学性提及"不算生成物声明（只看前 8 行，且形状要成短语）
        assertRole("docs/howto_generator.md", "Markdown",
                   header: ["# 如何写 code generator", "", "它会输出 code generated by 之类的字样"],
                   role: .documentation, criterion: .documentationPathSegment)
        // 同一份"讲生成器"的散文放在 .js 里也**不该**被判成生成物：判据只认编程语言的文件头
        assertRole("how_generator.js", "JavaScript",
                   header: ["// 这篇教程会教你输出 code generated by 之类的字样"],
                   role: .production, criterion: .productionLanguageOnly)
    }

    /// 声明式生成物判据只认**头部**：第 30 行才出现的 "DO NOT EDIT" 不参与判定。
    func testGeneratedHeaderOnlyLooksAtTheHeadOfTheFile() {
        var lines = [String](repeating: "let v = 1", count: 20)
        lines.append("// DO NOT EDIT")
        let decision = SourceFileRoleRule.decide(relativePath: "src/Manual.swift", language: "Swift",
                                                 headerLines: Array(lines.prefix(8)))
        XCTAssertEqual(decision.role, .production)
        XCTAssertEqual(decision.criterion, .productionPathSegment)
    }

    // MARK: - 未知：语言未登记家族 ⇒ 必须落到 unrecognized，不许由"看着像源码"兜底

    /// 语言表里每一种语言都要有家族归属；**唯一**允许未登记的是这里点名的 SQL。
    /// 新增语言而未在这里表态 ⇒ 本条红 —— 这正是"漏判必须显形"的机器形状。
    func testEverySupportedLanguageHasARoleFamily() {
        let unmappedByDesign: Set<String> = ["SQL"]
        var unmapped: [String] = []
        for language in SourceLanguageCatalog.supportedLanguages
        where SourceFileRoleRule.roleFamily(of: language) == "unmapped" {
            if unmappedByDesign.contains(language) == false { unmapped.append(language) }
        }
        XCTAssertTrue(unmapped.isEmpty, "语言表新增了没登记角色家族的语言：\(unmapped)")
        XCTAssertEqual(SourceFileRoleRule.roleFamily(of: "SQL"), "unmapped",
                       "SQL 的「故意不登记」是判据的一部分（裸 .sql 认不出是 schema/迁移/报表）")
    }

    func testUnmappedLanguageAndMissingLanguageBothLandInUnrecognized() {
        assertRole("src/mystery.unknownext", "SomeNewLanguage", role: .unrecognized,
                   criterion: .noRoleEvidence)
        // 失败态：连语言都没有（分类器不会交出这种文件，但判据本身要站得住）
        let noLanguage = SourceFileRoleRule.decide(relativePath: "random", language: nil)
        XCTAssertEqual(noLanguage.role, .unrecognized)
        XCTAssertTrue(noLanguage.evidence.contains("无语言"), "要说出为什么认不出：\(noLanguage.evidence)")
    }

    /// 只有语言证据（路径无线索）是**弱判定**：它落生产码档，但判据名字必须与硬证据分开。
    func testLanguageOnlyProductionIsFlaggedAsWeak() {
        assertRole("tools/scratchpad.swift", "Swift", role: .production, criterion: .productionLanguageOnly)
        assertRole("qa/manual/checks.swift", "Swift", role: .test, criterion: .testPathSegment)
    }

    // MARK: - 判据表自身：每条判据都得有人走，每条都得有一个角色

    /// 每一条判据都要有唯一的角色归属，且 `decide` 走出来的角色必须与它一致。
    func testEveryCriterionMapsToItsOwnRole() {
        for criterion in SourceRoleCriterion.allCases {
            XCTAssertNotNil(criterion.role, "\(criterion.rawValue) 没有角色归属")
        }
        for (criterion, probe) in CodeRoleProbes.byCriterion {
            let got = SourceFileRoleRule.decide(relativePath: probe.0, language: probe.1, headerLines: probe.2)
            XCTAssertEqual(got.role, criterion.role, "\(probe.0) 的角色与判据归属不一致")
        }
    }

    /// 每条判据都造一个能走到它的输入：判据表里留着一条没人走的分支，就是"看起来有、其实没实现"。
    func testEveryCriterionHasAReachableShape() {
        let probes = CodeRoleProbes.byCriterion
        for criterion in SourceRoleCriterion.allCases {
            guard let probe = probes[criterion] else {
                XCTFail("判据 \(criterion.rawValue) 没有对应用例 —— 表里留了死分支"); continue
            }
            XCTAssertEqual(SourceFileRoleRule.decide(relativePath: probe.0, language: probe.1,
                                                     headerLines: probe.2).criterion, criterion,
                           "输入 \(probe.0) 本该走到 \(criterion.rawValue)")
        }
    }

    // MARK: - 累计：恒等式与弱判定样本

    private func makeFile(_ relativePath: String, _ language: String, codeLines: Int = 2) -> ScannedSourceFile {
        var file = ScannedSourceFile(url: URL(fileURLWithPath: "/fixture/" + relativePath),
                                     relativePath: relativePath, language: language, lines: [],
                                     blankLineCount: 0, commentLineCount: 0,
                                     codeLineCount: codeLines, todoCount: 0, fixmeCount: 0)
        file.lines = (1...codeLines).map { SourceLine(number: $0, text: "v = 1", kind: .code) }
        return file
    }

    func testTallyKeepsEveryLineSomewhere() {
        let files = [makeFile("src/App.swift", "Swift", codeLines: 5),
                     makeFile("__tests__/App.test.js", "JavaScript", codeLines: 3),
                     makeFile("package-lock.json", "JSON", codeLines: 4),
                     makeFile("analytics/x.sql", "SQL", codeLines: 2),
                     makeFile("scratchpad.swift", "Swift", codeLines: 1)]
        let tally = SourceRoleTally(of: files)
        XCTAssertEqual(tally.attributedFileCount, files.count, "每个文件都要有一档，不许漏归类")
        XCTAssertEqual(tally.attributedCodeLines, 15, "行数守恒：分档之和必须等于全量")
        XCTAssertEqual(tally.files(.unrecognized), 1)
        XCTAssertEqual(tally.weakEvidenceFiles, 1)
        XCTAssertEqual(tally.criterionCounts[.productionPathSegment], 1)
        XCTAssertTrue(tally.weakEvidenceExamples == ["scratchpad.swift"], "弱判定要能点名：\(tally.weakEvidenceExamples)")
    }

    /// RD-63 · **点名样本只许由相对路径决定**，与文件被递进累计器的先后无关。
    /// 立案证据：GUI↔CLI 对表同一棵夹具树，`code.fileRoles.shares[0].samplePaths` 一个给
    /// `Cart.swift` 一个给 `Ledger.swift`，三趟里两趟对不表、而且方向会反过来
    /// ⇒ 旧写法是"按遇到顺序取前 N 个"，等于让并发调度的偶然决定屏上点谁的名。
    /// 期望值由测试**自己排序**算出来（独立真值），不是拿实现输出当答案。
    func testExamplesAreChosenByPathNotByEncounterOrder() {
        let names = ["src/Zeta.swift", "src/alpha.swift", "src/Mid.swift", "src/Beta.swift",
                     "src/Gamma.swift", "src/Delta.swift", "src/Epsilon.swift", "src/Theta.swift"]
        let forward = names.map { makeFile($0, "Swift") }
        let reversed = Array(forward.reversed())
        let expected = Array(names.sorted().prefix(SourceRoleTally.exampleLimit))
        XCTAssertLessThan(SourceRoleTally.exampleLimit, names.count, "样本上限必须真被撞到，否则这条在空转")
        for (label, files) in [("正序递", forward), ("逆序递", reversed)] {
            XCTAssertEqual(SourceRoleTally(of: files).share(.production).examples, expected,
                           "\(label) 点出来的名不一样 ⇒ 样本吃的是遇到顺序：\(names.sorted())")
        }
        XCTAssertEqual(expected.first, "src/Beta.swift", "上面那组的独立真值本身要能被反驳")
    }

    /// 未识别 / 弱判定 / 非生产内容仍在分母 —— 三条边界句都得进 `scanLimitations` 那条列表。
    func testTallyNotesNameTheBoundaryNotTheReading() {
        let files = [makeFile("src/App.swift", "Swift", codeLines: 5),
                     makeFile("analytics/x.sql", "SQL", codeLines: 2),
                     makeFile("scratchpad.swift", "Swift", codeLines: 1),
                     makeFile("docs/guide.md", "Markdown", codeLines: 7)]
        let tally = SourceRoleTally(of: files)
        let notes = tally.notes
        XCTAssertEqual(notes.count, 2, "未识别 + 分母未收窄，各一句：\(notes)")
        XCTAssertTrue(notes.contains { $0.contains("认不出角色") }, "\(notes)")
        XCTAssertTrue(notes.contains { $0.contains("未按角色收窄") && $0.contains("文档 1") })
        // 弱判定那句不占 scanLimitations —— 理由不是"那一档还没上屏"（RD-67 已把这一档
        // 接到屏上：`ProductionCodeScaleReadout.weakEvidenceHint` 读落盘的 weakEvidenceFiles），
        // 而是同一个数已经在两处出声、再挂一条边界就是把已量到的东西重复计成「没量准」。
        // 但它仍然必须在 roleLines 里备着（那一份带样本路径，上屏那一句没有）。
        XCTAssertTrue(notes.contains { $0.contains("只有语言证据") } == false, "\(notes)")
        XCTAssertTrue(tally.roleLines.contains { $0.contains("只有语言证据")
            && $0.contains("scratchpad.swift") }, "\(tally.roleLines)")
        // RD-67：这枚字段**已经落地**（`code.fileRoles` 八档全量、CLI 那一行读它），
        // 所以那句边界不许再说"要等字段"—— 把已有的东西说成没有，与把没有的说成已有，
        // 是同一条不诚实的两个方向（本仓踩过：把口径说成没量到，是反向不诚实）。
        let narrowed = notes.filter { $0.contains("未按角色收窄") }
        XCTAssertEqual(narrowed.count, 1, "分母未收窄那句只许有一条：\(notes)")
        let boundary = narrowed[0]
        XCTAssertTrue(boundary.contains("code.fileRoles"),
                      "既然字段已落盘，那句就必须点名可读数在哪：\(boundary)")
        for forbidden in ["需等", "清单见", "尚缺", "字段还没有"] {
            XCTAssertFalse(boundary.contains(forbidden),
                           "把已落地的读数说成没有 ⇒ 反向不诚实：\(forbidden) / \(boundary)")
        }
    }

    /// 一个生产码都不缺、也不缺任何线索时，**不许**出声（零命中不出声）。
    func testTallyStaysSilentWhenEveryFileHasHardEvidence() {
        let files = [makeFile("src/App.swift", "Swift", codeLines: 5),
                     makeFile("__tests__/App.test.js", "JavaScript", codeLines: 3)]
        XCTAssertEqual(SourceRoleTally(of: files).notes.filter { $0.contains("认不出角色") }.count, 0)
        XCTAssertTrue(SourceRoleTally(of: []).notes.isEmpty, "空扫描面不许编出句子")
    }


}

/// 每条判据一个**能走到它**的输入。两条用例共用同一张表：
/// `testEveryCriterionHasAReachableShape` 验"表里没有死分支"，
/// `testEveryCriterionMapsToItsOwnRole` 验"判据与角色的对应只有一份"。
enum CodeRoleProbes {
    static let byCriterion: [SourceRoleCriterion: (String, String?, [String])] = [
        .buildArtifactPath: ("compileout/x.js", "JavaScript", []),
        .backupEvidenceName: ("x.sql.bak", "SQL", []),
        .backupEvidencePath: ("backups/x.swift", "Swift", []),
        .lockFileName: ("yarn.lock", "JSON", []),
        .generatedPathSegment: ("src/protobuf/out/Thing.swift", "Swift", []),
        .generatedFileSuffix: ("x.pb.swift", "Swift", []),
        .generatedHeaderLine: ("x.js", "JavaScript", ["// Code generated by"]),
        .migrationShape: ("db/migrate/0001_x.sql", "SQL", []),
        .testPathSegment: ("__tests__/x.js", "JavaScript", []),
        .testFileNameShape: ("foo_test.go", "Go", []),
        .configurationPathSegment: ("config/x.swift", "Swift", []),
        .configurationDataLanguage: ("x.json", "JSON", []),
        .buildScriptLanguage: ("Makefile", "Makefile", []),
        .documentationExtension: ("README.md", "Markdown", []),
        .documentationPathSegment: ("docs/x.swift", "Swift", []),
        .productionPathSegment: ("src/x.swift", "Swift", []),
        .productionLanguageOnly: ("scratchpad.swift", "Swift", []),
        .noRoleEvidence: ("x.sql", "SQL", []),
    ]
}
