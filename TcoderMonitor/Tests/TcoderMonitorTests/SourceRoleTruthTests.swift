import XCTest
@testable import TcoderMonitor

/// OWNER: WS-R6 文件角色与扫描范围（RD-14）—— 角色判据的独立真值用例。
///
/// **独立真值 = 这个文件里手写的期望表**（`expected` 那些元组是我按判据文档一条条推出来的，
/// 不是跑实现抄回来的）。实现输出与这里不一致时，先怀疑实现，再怀疑这张表 ——
/// 反过来做就是把实现当规格。
///
/// 四态都在这里：正例（八档各一枚）、反例（合法写法不许误伤）、未知（语言未登记 / 认不出角色）、
/// 失败（路径没有任何语言证据）。
final class SourceRoleTruthTests: XCTestCase {

    // MARK: - 正例：七档 + 未识别，每档至少一枚，且判据名字必须对上

    private func assertRole(_ relativePath: String, _ language: String?, header: [String] = [],
                            role: SourceFileRole, criterion: SourceRoleCriterion,
                            file: StaticString = #filePath, line: UInt = #line) {
        let got = SourceFileRoleRule.decide(relativePath: relativePath, language: language, headerLines: header)
        XCTAssertEqual(got.role, role, "\(relativePath) 判成了 \(got.role.rawValue)（判据 \(got.criterion.rawValue)）",
                       file: file, line: line)
        XCTAssertEqual(got.criterion, criterion, "\(relativePath) 是靠 \(got.criterion.rawValue) 判的，"
            + "期望 \(criterion.rawValue)", file: file, line: line)
        XCTAssertFalse(got.evidence.isEmpty, "\(relativePath) 的判定必须带线索", file: file, line: line)
    }

    func testEachRoleHasAtLeastOnePositiveShape() {
