    private static let packageRoot: URL = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()   // Tests/TcoderMonitorTests
        .deletingLastPathComponent()   // Tests
        .deletingLastPathComponent()   // TcoderMonitor（包根）

    // MARK: - 独立真值（手写的账，不来自实现）

    /// 一条产出一行、不留空行也不写注释 ⇒ 那一档的 `codeLines == totalLines`。
    /// 唯一例外是 `grpc/Echo.swift` 的第 1 行（`// Code generated by …` 是注释行），
    /// 它单独记 5 总 / 4 码 —— 手写在下面，不留给实现去解释。
    private enum Truth {
        // 生产源码：两枚有路径证据、一枚只有语言证据（弱判定）
        static let productionFiles = 3
        static let productionCodeLines = 6 + 4 + 3           // 13
        static let productionWeakFiles = 1                  // 只有 tools/Counter.swift
        // 测试与夹具：一枚靠目录、一枚靠文件名形状（且它就住在 src/ 里）
        static let testFiles = 2
        static let testCodeLines = 5 + 4                    // 9
        // 生成物：一枚靠后缀 .pb.swift、一枚只靠文件头声明（那 5 行里 1 行是注释）
        static let generatedFiles = 2
        static let generatedCodeLines = 7 + 4               // 11
        static let generatedTotalLines = 7 + 5              // 12
        // 文档：一枚在 docs/ 里、一枚只靠 .md 后缀
        static let documentationFiles = 2
        static let documentationCodeLines = 5 + 4           // 9
        // 配置与结构化数据
        static let configurationFiles = 1
        static let configurationCodeLines = 3
        // 三档本轮没造证据 ⇒ 必须是「量到的 0」而不是缺席
        static let emptyBuckets: [SourceFileRole] = [.buildArtifact, .backupEvidence, .unrecognized]

        static var allFiles: Int {
            productionFiles + testFiles + generatedFiles + documentationFiles + configurationFiles
        }                                                                        // 10
        static var allCodeLines: Int {
            productionCodeLines + testCodeLines + generatedCodeLines
                + documentationCodeLines + configurationCodeLines
        }                                                                        // 45
        static var allTotalLines: Int { allCodeLines + 1 }                       // 46（Echo 那行注释）
    }

    /// 手写语料：十枚文件、五档有数、三档为零，且 `Widget` 这个 basename 跨了四档。
    private var corpus: [String: [String]] {
        [
            "src/App.swift": plain("let a", 6),
            "src/Widget.swift": plain("let w", 4),
            "tools/Counter.swift": plain("let c", 3),
            "tests/Widget.swift": plain("let t", 5),
            "src/test_upload.py": pythonish(4),
            "gen/Widget.pb.swift": plain("let g", 7),
            "grpc/Echo.swift": ["// Code generated by protoc-gen-go. DO NOT EDIT."] + plain("let e", 4),
            "docs/Widget.md": prose(5),
            "guide.md": prose(4),
            "config/app.yml": yaml(3),
        ]
    }

    private func plain(_ stem: String, _ n: Int) -> [String] { (1...n).map { "\(stem)\($0) = \($0)" } }
    private func pythonish(_ n: Int) -> [String] { (1...n).map { "value_\($0) = \($0)" } }
    private func prose(_ n: Int) -> [String] { (1...n).map { "Paragraph line \($0)" } }
    private func yaml(_ n: Int) -> [String] { (1...n).map { "key\($0): \($0)" } }

    // MARK: - 取数：写夹具 → 走产品侧同一条扫描口

    private func scan(_ files: [String: [String]], tag: String) async throws -> CodeMetrics {
        let fm = FileManager.default
        let root = Self.packageRoot.appendingPathComponent(
            ".scratch/r16-rolefields-\(tag)-\(UUID().uuidString)", isDirectory: true)
        try fm.createDirectory(at: root, withIntermediateDirectories: true)
        addTeardownBlock { try? fm.removeItem(at: root) }
        for (path, lines) in files {
            let url = root.appendingPathComponent(path)
            try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try Data((lines.joined(separator: "\n") + "\n").utf8).write(to: url, options: .atomic)
        }
        return try await FileSystemCodeAnalyzer().analyze(root: root, options: .default)
    }

    private func report(_ metrics: CodeMetrics) -> ProjectReport {
        var full = ProjectReport(project: MonitoredProject(name: "r16夹具", path: "/scratch/r16"))
        full.code = metrics
        return full
    }

    // MARK: - ⓪ 先自证手写账没数错（数错了下面的断言都不作数）

    func testHandCountedTruthAgreesWithTheFixtureItself() {
        XCTAssertEqual(corpus.count, Truth.allFiles, "夹具枚数与手写账不符，先修夹具")
        var code = 0
        var total = 0
        for (path, lines) in corpus {
            total += lines.count
            code += lines.filter { $0.hasPrefix("//") == false }.count
            XCTAssertFalse(lines.contains(where: { $0.trimmingCharacters(in: .whitespaces).isEmpty }),
                           "\(path) 里有空行，手写账是按没有空行数的")
        }
        XCTAssertEqual(total, Truth.allTotalLines)
        XCTAssertEqual(code, Truth.allCodeLines, "只有 Echo.swift 的头一行是注释，别处不许再多")
    }

    // MARK: - ① 八档全量：每档一枚、数值 == 手写账，零读数是「量到的 0」

    func testEightBucketsAreAllListedWithHandCountedNumbers() async throws {
        let metrics = try await scan(corpus, tag: "buckets")
        let roles = try XCTUnwrap(metrics.fileRoles, "真扫过一次却没落角色分档 ⇒ 写字段那一行没生效")
        XCTAssertEqual(roles.shares.count, SourceFileRole.allCases.count,
                       "八档必须全量列出，缺档会被读成「没量到」")
        XCTAssertEqual(roles.shares.map(\.role), SourceFileRole.allCases.map(\.rawValue),
                       "顺序必须跟着枚举走，不要在别处再写一份档名名单")
        for role in Truth.emptyBuckets {
            let share = try? XCTUnwrap(roles.share(for: role))
            XCTAssertEqual(share?.fileCount, 0, "\(role.rawValue) 本轮没造证据 ⇒ 量到的 0，不是缺席")
            XCTAssertEqual(share?.samplePaths, [], "量过了而真的没有 ⇒ 空数组，不许 nil")
        }
        assertBucket(roles.share(for: .production), files: Truth.productionFiles,
                     code: Truth.productionCodeLines, total: Truth.productionCodeLines)
        assertBucket(roles.share(for: .test), files: Truth.testFiles,
                     code: Truth.testCodeLines, total: Truth.testCodeLines)
        assertBucket(roles.share(for: .generated), files: Truth.generatedFiles,
                     code: Truth.generatedCodeLines, total: Truth.generatedTotalLines)
        assertBucket(roles.share(for: .documentation), files: Truth.documentationFiles,
                     code: Truth.documentationCodeLines, total: Truth.documentationCodeLines)
        assertBucket(roles.share(for: .configuration), files: Truth.configurationFiles,
                     code: Truth.configurationCodeLines, total: Truth.configurationCodeLines)
    }

    private func assertBucket(_ share: CodeFileRoleShare?, files: Int, code: Int, total: Int,
                              _ message: String = "") {
        if share == nil { XCTFail("这一档没出现在八档清单里（缺档＝没量到）"); return }
        XCTAssertEqual(share?.fileCount, files, message)
        XCTAssertEqual(share?.codeLines, code, message)
        XCTAssertEqual(share?.totalLines, total, message)
    }

    // MARK: - ①′ 同名不同档：证明不是按 basename 猜的

    func testSameBasenameLandsInFourDifferentBuckets() async throws {
        let scanned = try await scan(corpus, tag: "basename")
        let roles = try XCTUnwrap(scanned.fileRoles)
        for (role, path) in [
            (SourceFileRole.production, "src/Widget.swift"), (.test, "tests/Widget.swift"),
            (.generated, "gen/Widget.pb.swift"), (.documentation, "docs/Widget.md"),
        ] {
            let share = try XCTUnwrap(roles.share(for: role), "\(role.rawValue) 那一档不见了")
            XCTAssertTrue(share.samplePaths?.contains(path) == true,
                          "同名 Widget 的 \(path) 没出现在 \(role.rawValue) 档的样本里：\(share.samplePaths ?? [])")
        }
        // 反查：这一档里不许混进别的档的同名文件
        XCTAssertFalse(roles.share(for: .test)?.samplePaths?.contains("src/Widget.swift") ?? true,
                       "生产码那份被搬进测试档了 ⇒ 分档不是按路径判的")
    }

    // MARK: - ② 恒等式（按构造成立的那两条），外加与 totalFiles 的对账

    func testFileCountAndLineIdentitiesHoldAgainstTheScanPopulation() async throws {
        let metrics = try await scan(corpus, tag: "identity")
        let roles = try XCTUnwrap(metrics.fileRoles)
        let summed = roles.shares.map(\.fileCount).reduce(0, +)
        XCTAssertEqual(summed, roles.attributedFileCount ?? -1,
                       "恒等式 shares 求和 == attributedFileCount 破了")
        XCTAssertEqual(roles.attributedFileCount, metrics.totalFiles,
                       "本次扫描每个文件都归得上档 ⇒ 与 totalFiles 必须相等，差额出现即判据漏了")
        XCTAssertEqual(roles.shares.map(\.codeLines).reduce(0, +), metrics.codeLines,
                       "各档代码行之和必须等于同一批文件的 codeLines（两份账数的是同一个总体）")
        XCTAssertEqual(roles.shares.map(\.totalLines).reduce(0, +), metrics.totalLines)
        XCTAssertNil(CLIScoreText.fileRoleLines(report(metrics))
            .first { $0.contains("对不平") }, "两个数相等却喊对不平 ⇒ 那句话成了噪音")
    }

    // MARK: - ①″ 判据分布与弱判定：弱判定数 == 那条判据的命中数，而不是档位大小

    func testWeakEvidenceIsTheLanguageOnlyCriterionNotTheBucketSize() async throws {
        let scanned = try await scan(corpus, tag: "weak")
        let roles = try XCTUnwrap(scanned.fileRoles)
        let production = try XCTUnwrap(roles.share(for: .production))
        let hits = try XCTUnwrap(roles.criterionCounts?[SourceRoleCriterion.productionLanguageOnly.rawValue])
        XCTAssertEqual(production.weakEvidenceFiles, hits,
                       "弱判定必须等于「只有语言证据」那条判据的命中数")
        XCTAssertNotEqual(production.weakEvidenceFiles, production.fileCount,
                          "手写夹具特意让两数不相等；相等说明字段被填成了档位大小")
        XCTAssertEqual(production.weakEvidenceFiles, Truth.productionWeakFiles)
        for role in SourceFileRole.allCases where role != .production {
            XCTAssertNil(roles.share(for: role)?.weakEvidenceFiles,
                         "\(role.rawValue) 档不适用这一问，写 0 会被读成「这一档没有弱判定」")
        }
    }

    /// 反例①（有牙证明）：把 `weakEvidenceFiles` 填成生产码档的文件数，对账判据必须红。
    func testWeakEvidenceCounterexampleIsCaughtByTheSameReconciliation() throws {
        let good = CodeFileRoleShare(role: SourceFileRole.production.rawValue, fileCount: 3,
                                     codeLines: 13, totalLines: 13, weakEvidenceFiles: 1,
                                     samplePaths: ["src/App.swift"])
        let bad = CodeFileRoleShare(role: good.role, fileCount: good.fileCount, codeLines: good.codeLines,
                                    totalLines: good.totalLines, weakEvidenceFiles: good.fileCount,
                                    samplePaths: good.samplePaths)
        let criteria = [SourceRoleCriterion.productionLanguageOnly.rawValue: 1]
        XCTAssertEqual(reconcile(good, criteria), [], "正例被误判，说明比对器在挑形状而不是挑数")
        XCTAssertEqual(reconcile(bad, criteria),
                       ["弱判定数与判据 productionLanguageOnly 的命中数不等"],
                       "把弱判定填成档位大小没被抓到 ⇒ 这条判据是摆设")
    }

    /// 纯函数对账口：字段自己不带真值，所以比对写在这里，正反例都过它。
    private func reconcile(_ share: CodeFileRoleShare, _ criteria: [String: Int]?) -> [String] {
        guard share.role == SourceFileRole.production.rawValue else { return [] }
        let hits = criteria?[SourceRoleCriterion.productionLanguageOnly.rawValue]
        guard let weak = share.weakEvidenceFiles else { return ["弱判定数缺席（没量到）"] }
        guard let hits else { return ["判据分布缺席（没量到）"] }
        return weak == hits ? [] : ["弱判定数与判据 productionLanguageOnly 的命中数不等"]
    }

    // MARK: - ②′/④ 反例②：有文件没归上档时那句差额必须出声

    func testAttributedShortfallAgainstTotalFilesIsSpelledOut() throws {
        let partial = CodeFileRoles(shares: [
            CodeFileRoleShare(role: SourceFileRole.production.rawValue, fileCount: 4, codeLines: 40,
                              totalLines: 44, weakEvidenceFiles: 0, samplePaths: ["src/a.swift"]),
        ], criterionCounts: nil, attributedFileCount: 4)
        var metrics = CodeMetrics()
        metrics.totalFiles = 5
        metrics.codeLines = 40
        metrics.fileRoles = partial
        let text = CLIScoreText.render(report(metrics), exit: .ok)
        XCTAssertTrue(text.contains("对不平"), "有文件没归上档却静默抹平了：\n\(text)")
        XCTAssertTrue(text.contains("八档合计 4 个文件，而本次扫到 5 个，相差 1 个"),
                      "那句必须带三个真数，不许只喊不平：\n\(text)")
        XCTAssertTrue(text.contains("生产源码 4 个 / 40 代码行 · 弱判定 0 个"),
                      "喊不平的那一句旁边，正常那句也得带上字段里的真数：\n\(text)")
    }

    // MARK: - ③ 三态：旧 JSON 缺整键 ⇒ nil；有字段但某档缺席 ⇒ 读作没量到，不许补 0

    func testOldJSONWithoutTheWholeKeyDecodesAsNilAndStaysSilent() throws {
        var metrics = CodeMetrics()
        metrics.fileRoles = nil
        let data = try CLIScanEncoded(metrics)
        XCTAssertFalse(String(decoding: data, as: UTF8.self).contains("fileRoles"),
                       "没量到就该整键缺席，而不是写一个空 shares 数组")
        let back = try JSONDecoder.tcoderReportDecoder().decode(CodeMetrics.self, from: data)
        XCTAssertNil(back.fileRoles, "缺键 = 这份报告没有这个读数，不许被补成空数组或全 0")
        XCTAssertEqual(CLIScoreText.fileRoleLines(report(back)), [], "旧报告不许凭空打一句分档")
    }

    func testAbsentBucketMeansNotMeasuredWhileZeroMeansMeasuredEmpty() throws {
        var metrics = CodeMetrics()
        metrics.totalFiles = 0
        metrics.fileRoles = CodeFileRoles(
            shares: [CodeFileRoleShare(role: SourceFileRole.test.rawValue, fileCount: 0,
                                       codeLines: 0, totalLines: 0, weakEvidenceFiles: nil,
                                       samplePaths: [])],
            criterionCounts: nil, attributedFileCount: 0)
        let roles = try XCTUnwrap(metrics.fileRoles)
        XCTAssertNotNil(roles.share(for: .test), "0 也要占一行：那是量过了而真的是空")
        XCTAssertNil(roles.share(for: .production), "这一档根本没出现在清单里 = 没量到")
        let lines = CLIScoreText.fileRoleLines(report(metrics))
        XCTAssertEqual(lines.count, 1)
        XCTAssertTrue(lines[0].contains("未记录"), "缺档被渲染成 0 了：\(lines[0])")
        XCTAssertFalse(lines[0].contains("生产源码 0 个"), lines[0])
    }

    private func CLIScanEncoded(_ metrics: CodeMetrics) throws -> Data {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        return try encoder.encode(metrics)
    }

    // MARK: - 判据分布：这一档是靠什么认出来的，必须数得出来

    func testCriterionCountsNameEveryCriterionThatFired() async throws {
        let scanned = try await scan(corpus, tag: "criteria")
        let roles = try XCTUnwrap(scanned.fileRoles)
        let counts = try XCTUnwrap(roles.criterionCounts)
        let expected: [SourceRoleCriterion: Int] = [
            .productionPathSegment: 2, .productionLanguageOnly: 1,
            .testPathSegment: 1, .testFileNameShape: 1,
            .generatedFileSuffix: 1, .generatedHeaderLine: 1,
            .documentationPathSegment: 1, .documentationExtension: 1,
            .configurationPathSegment: 1,
        ]
        XCTAssertEqual(counts, expected.map { ($0.key.rawValue, $0.value) }
                       .reduce(into: [String: Int]()) { partial, pair in partial[pair.0] = pair.1 })
        XCTAssertEqual(counts.values.reduce(0, +), Truth.allFiles,
                       "判据命中之和必须等于参与分档的文件数，否则有文件是被「无判据」归的档")
        let paths = roles.shares.flatMap { $0.samplePaths ?? [] }
        XCTAssertFalse(paths.isEmpty)
        XCTAssertTrue(paths.allSatisfy { $0.count <= 200 && $0.hasPrefix("/") == false },
                      "样本必须是相对路径：\(paths)")
        for share in roles.shares {
            XCTAssertLessThanOrEqual(share.samplePaths?.count ?? 0, SourceRoleTally.exampleLimit,
                                     "\(share.role) 档样本超了引擎那把尺子")
        }
    }

    // MARK: - ⑤ 结构守卫：这一族字段必须既有写者又有读者（各配元测试证明有牙）

    private func witnesses(_ files: [(path: String, content: String)]) -> (writers: [String], readers: [String]) {
        var writers: [String] = []
        var readers: [String] = []
        for file in files {
            let code = file.content.components(separatedBy: "\n").filter(SurfaceScanKit.isCode)
            if code.contains(where: { $0.contains("metrics.fileRoles =") }) { writers.append(file.path) }
            if code.contains(where: { $0.contains("code.fileRoles") }) { readers.append(file.path) }
        }
        return (writers, readers)
    }

    func testFieldHasExactlyOneWriterAndOneProductionReader() throws {
        let found = witnesses(try SurfaceScanKit.sourceFiles(under: ""))
        XCTAssertEqual(found.writers, ["Services/Code/FileSystemCodeAnalyzer.swift"],
                       "写字段只能有一处（直传 tally），多一处就是第二把尺子：\(found.writers)")
        XCTAssertTrue(found.readers.contains("Services/CLI/CLIScoreText.swift"),
                      "字段没有生产读者 ⇒ 回到 RD-14 立案时那个「只活在句子里」的状态：\(found.readers)")
    }

    func testMeta_witnessScannerCatchesBothBrokenShapes() throws {
        let real = try SurfaceScanKit.sourceFiles(under: "")
        let base = witnesses(real)
        XCTAssertEqual(base.writers.count, 1, "真源码连基线都不成立，元测试不作数")
        XCTAssertFalse(base.readers.isEmpty, "基线里就该有读者")
        let analyzer = "Services/Code/FileSystemCodeAnalyzer.swift"
        let stripped = witnesses(real.filter { $0.path != analyzer })
        XCTAssertEqual(stripped.writers, [], "擦掉唯一那处直传而守卫仍报有写者 ⇒ 没牙")
        let cli = "Services/CLI/CLIScoreText.swift"
        let blind = witnesses(real.map { file in
            file.path == cli
                ? (path: file.path, content: file.content
                    .replacingOccurrences(of: "code.fileRoles", with: "code.codeLines"))
                : file
        })
        XCTAssertFalse(blind.readers.contains(cli), "CLI 不再读那枚字段却没报 ⇒ 没牙")
        let commentOnly = witnesses([(path: "Views/Dummy.swift",
                                      content: "// 读者见 code.fileRoles\nimport Foundation")])
        XCTAssertEqual(commentOnly.readers, [], "注释凑成了读者 ⇒ 这条守卫会在文档里找证据")
    }
}

/// ⑥ CLI↔测试驱动分析器对账：**真扫一次本仓**，走交付用的同一套 coder 再解回来逐字段比。
///
/// 复用 `SelfScanHarnessCase` 那台一次扫描六个分析器的缓存，全仓只扫一遍；
/// 不启动 App（AGENTS §3 横切约束 2），读数一律由测试驱动分析器取。
final class CodeFileRoleRealScanTests: SelfScanHarnessCase {

    func testSelfScanFieldSurvivesTheCLIEncodingRoundTrip() async throws {
        let metrics = try await selfScan().code
        let roles = try XCTUnwrap(metrics.fileRoles, "扫本仓没落角色分档 ⇒ 写字段那一行没生效")
        XCTAssertEqual(roles.shares.count, SourceFileRole.allCases.count)
        XCTAssertEqual(roles.shares.map(\.fileCount).reduce(0, +), roles.attributedFileCount ?? -1)

        var full = ProjectReport(project: MonitoredProject(name: "本仓", path: Self.repoRoot.path))
        full.code = metrics
        let json = try CLIScan.json(full, compact: true)
        XCTAssertTrue(json.contains("\"fileRoles\""),
                      "scan 落的 JSON 里没有 code.fileRoles ⇒ 读 JSON 的人还是拿不到")
        let decoded = try JSONDecoder.tcoderReportDecoder().decode(ProjectReport.self, from: Data(json.utf8))
        XCTAssertEqual(decoded.code?.fileRoles, roles, "JSON 里那一份与分析器返回的不一致")
        XCTAssertEqual(decoded.code?.fileRoles?.shares.flatMap { $0.samplePaths ?? [] }.count,
                       roles.shares.flatMap { $0.samplePaths ?? [] }.count)
        print("【R16 真扫本仓】八档 \(roles.shares.map { "\($0.role)=\($0.fileCount)" }.joined(separator: " "))"
            + " · 生产码 \(roles.share(for: .production)?.codeLines ?? -1) 行"
            + " · 弱判定 \(roles.share(for: .production)?.weakEvidenceFiles ?? -1)"
            + " · 参与分档 \(roles.attributedFileCount ?? -1) / totalFiles \(metrics.totalFiles)")
    }
}
